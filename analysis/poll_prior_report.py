"""Write docs/poll_priors.md: the poll-start sensitivity (v3) of Poland, Brazil, Mexico and Hungary, every number read from the
published site data, the poll CSVs and the v3 configs.

    uv run python analysis/poll_prior_report.py
"""

from __future__ import annotations

import json
import sys
import tomllib
from datetime import datetime
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

import poll_priors as pp  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "site" / "data"
Z90 = 1.6448536269514722
# id -> (headline race, results key, label)
ELECTIONS = {
    "pl2025r1": ("winner", {"year": 2025, "round": 1}, "Poland 2025 round 1 (Trzaskowski vs Nawrocki)"),
    "pl2025r2": ("winner", {"year": 2025, "round": 2}, "Poland 2025 runoff (Trzaskowski vs Nawrocki)"),
    "br2022r1": ("br", {"year": 2022, "round": 1}, "Brazil 2022 round 1 (Lula vs Bolsonaro)"),
    "br2022r2": ("br", {"year": 2022, "round": 2}, "Brazil 2022 runoff (Lula vs Bolsonaro)"),
    "br2026r1": ("br", {"year": 2026, "round": 1}, "Brazil 2026 round 1 (Lula vs Flávio Bolsonaro)"),
    "br2026r2": ("br", {"year": 2026, "round": 2}, "Brazil 2026 runoff (Lula vs Flávio Bolsonaro)"),
    "mx2024": ("mx", {"year": 2024}, "Mexico 2024 (Sheinbaum vs Gálvez)"),
    "hu2026": ("seats", {"year": 2026}, "Hungary 2026 (Tisza vs Fidesz-KDNP; list vote, and seats race)"),
}


def t(s):
    return datetime.fromisoformat(s.replace("Z", "+00:00")) if s else None


def band_stats(rows: list[dict], share: str, sd: str, final: float) -> tuple[float | None, float | None]:
    d = pd.DataFrame(rows)
    d = d[d["counted"].between(0.01, 0.95, inclusive="right") & d[share].notna() & d[sd].notna()]
    if d.empty:
        return None, None
    inside = ((d[share] - Z90 * d[sd]) <= final) & (final <= (d[share] + Z90 * d[sd]))
    return float(inside.mean()), float(100 * (d[share] - final).abs().mean())


def pct(x, n=1):
    return "–" if x is None else f"{100 * x:.{n}f}"


def main() -> None:
    rows = []
    for eid, (head, key, label) in ELECTIONS.items():
        cfg = tomllib.loads((ROOT / "configs" / f"{eid}_v3.toml").read_text())
        est = cfg["poll"]
        st = json.loads((DATA / eid / "stats.json").read_text())
        tl = json.loads((DATA / eid / "timeline.json").read_text())[head]
        v3 = st["sensitivities"]["v3"]
        c, d, f, a, b = pp.TARGETS[eid]
        res = pp.HIST[c][0]
        fin = pp.official(res, key, a, b)
        s = (st.get("settle_gated") or {}).get(head) or {}
        s0 = (st.get("settle") or {}).get(head) or {}
        mc = ((st.get("market_classification") or {}).get("by_race") or {}).get(head) or {}
        gate = t(s.get("gate") or s0.get("gate"))
        v1_model = s.get("model") or s0.get("model")
        v1_min = round((t(v1_model) - gate).total_seconds() / 60) if v1_model and gate else None
        b3 = v3["by_race"][head]
        share_final = fin if head not in ("seats",) else None
        if head == "seats":                                # the poll is for the list vote: score the list race too
            lst = v3["by_race"]["list"]
        else:
            lst = b3
        tl_list = json.loads((DATA / eid / "timeline.json").read_text())["list"] if head == "seats" else tl
        race = "list" if head == "seats" else head
        cov1, mae1 = band_stats(tl_list, "share", "sd", fin)
        k = {"share": "share_sens_v3", "sd": "sd_sens_v3"}
        cov3, mae3 = band_stats(tl_list, k["share"], k["sd"], fin)
        p_pre = v3.get("precount", {}).get("P_headline", v3.get("precount", {}).get("P_list_tisza_from_poll_alone"))
        outcome = mc.get("outcome_a")
        if outcome is None:
            outcome = fin > 0.5
        rows.append({"id": eid, "label": label, "poll": est["two_way"], "base": est.get("prior_base", est.get("prior_base_list")),
                     "sd": est["sd"], "n_polls": est["n_polls"], "n_err": est["n_errors"], "official": fin, "p_pre": p_pre, "outcome": bool(outcome),
                     "v1_min": v1_min, "v3_min": b3.get("settle_90_from_gate_min"), "pm": s.get("polymarket") or s0.get("polymarket"),
                     "gate": s.get("gate") or s0.get("gate"), "v1": v1_model, "v3": b3.get("settle_90_gated"),
                     "cov1": cov1, "cov3": cov3, "mae1": mae1, "mae3": mae3, "race": race, "early_v3": est.get("pollsters")})
    err = {}
    for c in ("pl", "br", "mx", "hu"):
        err[c] = pp.errors(c, "2100-01-01")
    L = ["# Poll start: final polls as the starting estimate (sensitivity v3)", "",
         "Generated by `analysis/poll_prior_report.py` from the published site data, the poll tables in `data_public/` and the `configs/<id>_v3.toml` files. "
         "Written after every one of these results was known: **a sensitivity, not a forecast**. v1 stays the headline in every replay; the dashed `v3` line "
         "and its own 90% mark sit next to it (Show bar, scrubber).", "",
         "## What it is", "",
         "The same model as v1 (same prior, `tau`, `rho`, `kappa`, same count states), started from the final polls instead of the previous election alone "
         "(the idea of Germany v3, `docs/germany.md`, without re-fitting anything). The rule was written in `analysis/poll_priors.py` before any of these nights was "
         "replayed with it:", "",
         "1. **Poll average.** Every poll of the country's table (Wikipedia, CC BY-SA, one row per poll with pollster, fieldwork dates and sample as printed, "
         "`data_public/<cc>_polls_<year>.csv`) whose fieldwork ended in the 14 days before election day, so it was published before the vote. For each poll the "
         "two-way share of side A, A / (A + B), uses the columns printed (undecided and others drop out); the average is the plain mean, no weighting.",
         "2. **Poll error.** The same average for every earlier election of that country with a usable poll table, against the official result's two-way share "
         "(`data_public/<cc>_poll_results.csv`). The sd of the starting estimate is the root-mean-square of those errors, bias not corrected, no floor.",
         "3. **Start.** `brunder.nowcast.Params.swing_prior_mean / swing_prior_sd` (the US poll model's mechanism): mean = poll two-way share minus the prior's "
         "vote-weighted two-way share, sd from step 2. The counted votes' own swing takes over as they arrive; `count_scaled_terms` lets the reporting-order error "
         "`tau` enter in proportion to the weight the counted votes have in the swing, so **before any count the uncertainty is the poll error alone** and the chance exists from poll close. "
         "Brazilian state races use the national swing prior with the full state-deviation terms (a state's own deviation is not a poll error). "
         "Hungary's district and list models share one national error, so seats and list move together.", "",
         "No count, price or exit poll of the night is an input. The settings of v1 are not re-fitted, so this isolates what the polls add.", "",
         "## Result per election", "",
         "Minutes are from the first minute with at least 1% counted until the chance stayed at or above 0.9 on the eventual winner "
         "(the site's rule; 0 = already there when 1% was in). `P at close` is v3's chance of side A before any count (Hungary: the list chance from the poll alone, "
         "the seat model needs a count publication, so its first v3 value is the first publication at 18:00 UTC). 90% coverage and mean absolute error are over 1% < counted ≤ 95% "
         "(Hungary: the list share).", "",
         "| election | poll A share | prior A share | poll sd (elections) | official A share | poll error | P(A) at close | A won | 90% v1 / v3 (min) | coverage v1 / v3 | MAE pt v1 / v3 |",
         "|---|---:|---:|---:|---:|---:|---:|:-:|---:|---:|---:|"]
    for r in rows:
        L.append(f"| {r['label']} | {pct(r['poll'])} ({r['n_polls']} polls) | {pct(r['base'])} | {pct(r['sd'])} ({r['n_err']}) | {pct(r['official'])} | "
                 f"{100 * (r['official'] - r['poll']):+.1f} | {pct(r['p_pre'], 0)}% | {'yes' if r['outcome'] else 'no'} | "
                 f"{r['v1_min']} / {r['v3_min']:.0f} | {pct(r['cov1'], 0)}% / {pct(r['cov3'], 0)}% | {r['mae1']:.2f} / {r['mae3']:.2f} |")
    L += ["", "## Reading, election by election", ""]
    for r in rows:
        right = (r["p_pre"] > 0.5) == r["outcome"]
        d = (r["v3_min"] or 0) - (r["v1_min"] or 0)
        cmp_ = "the same time" if abs(d) < 1.5 else (f"{abs(d):.0f} minutes {'later' if d > 0 else 'sooner'}")
        L.append(f"- **{r['label']}**: the poll start favoured the {'right' if right else 'wrong'} side "
                 f"({pct(r['p_pre'], 0)}% for A before any count; A {'won' if r['outcome'] else 'lost'}), the poll average missed A's two-way share by "
                 f"{abs(100 * (r['official'] - r['poll'])):.1f} points. v3 stayed at or above 0.9 from {r['v3_min']:.0f} minutes after 1% counted, v1 from {r['v1_min']} "
                 f"(v3 {cmp_}).")
    L += ["", "Headline race: the national winner race (Poland, Brazil, Mexico) and the seats race (Hungary; its list-vote race is scored for the share columns). "
          "Minutes use the same definition for both versions.", "", "## Poll error by earlier election", "",
          "Poll average (last 14 days) against the official result, two-way share of the named side; error = official − poll, in points. "
          "Rounds are pooled; an election is used only for targets held after it.", ""]
    names = {"pl": "Poland", "br": "Brazil", "mx": "Mexico", "hu": "Hungary"}
    for c, d in err.items():
        L += [f"**{names[c]}**", "", "| election | polls | poll | official | error (pt) |", "|---|---:|---:|---:|---:|"]
        for _, r in d.iterrows():
            L.append(f"| {r['election']} | {int(r['n_polls'])} | {100 * r['poll_two_way']:.1f} | {100 * r['official_two_way']:.1f} | {100 * r['error']:+.1f} |")
        L.append("")
    L += ["## Data and caveats", "",
          "- Poll tables come from English Wikipedia (some earlier ones from the Spanish page or the election article, named in each CSV header together with the revision "
          "id and the table choice); the polls are the pollsters' own. Dates and samples are as printed; where a page prints none the CSV says so.",
          "- Mexico 2012 prints only the month, so its three releases flagged as the final pre-election polls are used; Mexico 2006 prints the publication date "
          "(no fieldwork dates). Hungary 2014 and 2018 have two to four polls in the last 14 days; Hungarian polls are decided voters.",
          "- Each earlier election's A / B pair is fixed in `analysis/poll_priors.py` (Mexico: the left candidate against all other main candidates, as the model's prior does; "
          "Hungary: Fidesz-KDNP against the runner-up list; Brazil and Poland: the two sides of the replay). Few elections per country: the sd is a rough guide, and an error of "
          "the same sign three times (Mexico) or a very large one (Brazil 2014, Hungary 2022) moves it a lot.",
          "- State races in Brazil use the national poll swing; no state polls are used.",
          "- It is retrospective and tuned to nothing: the rule was fixed before the replays, and v1, the headline, is never changed."]
    (ROOT / "docs" / "poll_priors.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[L.index("## Result per election"):L.index("## Poll error by earlier election")]))


if __name__ == "__main__":
    main()
